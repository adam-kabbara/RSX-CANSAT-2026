void HAL_UART_RxCpltCallback(UART_HandleTypeDef* huart)
{
	if(huart->Instance == USART1)
	{
		if(!cmd_ready)
		{
			if(discard_flag)
			{
				if(rx_byte == '\r' || rx_idx == sizeof(rx_buff))
				{
					discard_flag = 0;
				}
			}
			else
			{
				if(rx_byte == '\r')
				{
					rx_buff[rx_idx] = '\0';
					cmd_ready = 1;
					rx_idx = 0;
				}
				else
				{
					rx_buff[rx_idx++] = rx_byte;
					if(rx_idx > sizeof(rx_buff))
					{
						rx_idx = 0;
					}
				}
			}
		}
		else
		{
			discard_flag = 1;
		}

		HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
	}
}
